#!/usr/bin/env python3
"""Embed GIF files in C headers, so the GIFs are flashed with the sketch.

Usage:
  python3 gif_to_header.py <out_dir> <file.gif> [<file.gif> ...]

Each file "name.gif" becomes "<out_dir>/otto_name.h" with the array
kOtto_name[] and its length kOtto_name_len.
"""
import pathlib
import sys


def main() -> None:
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    out_dir = pathlib.Path(sys.argv[1])
    out_dir.mkdir(parents=True, exist_ok=True)
    for path in map(pathlib.Path, sys.argv[2:]):
        data = path.read_bytes()
        name = path.stem
        header = out_dir / f"otto_{name}.h"
        with header.open("w") as f:
            f.write(f"// Generated by tools/gif_to_header.py from {path.name}. Do not edit.\n")
            f.write("// Otto emoji art: MIT license, see tools/otto/LICENSE.\n")
            f.write("#pragma once\n#include <stdint.h>\n\n")
            f.write(f"static const uint32_t kOtto_{name}_len = {len(data)};\n")
            f.write(f"static const uint8_t kOtto_{name}[] = {{\n")
            for i in range(0, len(data), 24):
                f.write("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",\n")
            f.write("};\n")
        print(f"{header}: {len(data)} bytes")


if __name__ == "__main__":
    main()
