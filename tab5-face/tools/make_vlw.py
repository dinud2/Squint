#!/usr/bin/env python3
"""Convert a TTF font to an anti-aliased VLW font in a C header (for M5GFX / LovyanGFX).

Usage:
  pip install pillow
  python3 make_vlw.py <font.ttf> <pixel_size> <symbol_name> <out.h>

Example:
  python3 make_vlw.py MPLUSRounded1c-ExtraBold.ttf 96 kFontTitle ../fonts/font_title.h

Only printable ASCII (space to ~) is included, to keep flash use small.
"""
import struct
import sys

from PIL import Image, ImageDraw, ImageFont


def build_vlw(ttf_path: str, size: int) -> bytes:
    font = ImageFont.truetype(ttf_path, size)
    ascent, descent = font.getmetrics()
    glyphs = []
    for code in range(0x20, 0x7F):
        ch = chr(code)
        advance = round(font.getlength(ch))
        left, top, right, bottom = font.getbbox(ch, anchor="ls")
        w, h = max(0, right - left), max(0, bottom - top)
        if code == 0x20 or w == 0 or h == 0:
            glyphs.append((code, 0, 0, advance, 0, 0, b""))
            continue
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255, anchor="ls")
        glyphs.append((code, h, w, advance, -top, left, img.tobytes()))

    out = bytearray()
    # Header: glyph count, version, size, unused, ascent, descent (big-endian).
    out += struct.pack(">6i", len(glyphs), 11, size, 0, ascent, descent)
    # Glyph table: unicode, height, width, xAdvance, dY, dX, padding.
    for code, h, w, adv, dy, dx, _ in glyphs:
        out += struct.pack(">7i", code, h, w, adv, dy, dx, 0)
    for *_, bitmap in glyphs:
        out += bitmap
    return bytes(out)


def write_header(data: bytes, symbol: str, path: str, source: str, size: int) -> None:
    with open(path, "w") as f:
        f.write(f"// Generated by tools/make_vlw.py from {source} at {size} px. Do not edit.\n")
        f.write("// Font license: SIL Open Font License 1.1 (see src/fonts/OFL-NOTICE.txt).\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f"static const uint32_t {symbol}_len = {len(data)};\n")
        f.write(f"static const uint8_t {symbol}[] = {{\n")
        for i in range(0, len(data), 24):
            f.write("  " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",\n")
        f.write("};\n")


if __name__ == "__main__":
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    ttf, px, sym, out_path = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4]
    vlw = build_vlw(ttf, px)
    write_header(vlw, sym, out_path, ttf.split("/")[-1], px)
    print(f"{out_path}: {len(vlw)} bytes")
